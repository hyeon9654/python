# 비트코인 가격 변동성과 시장 심리 분석
# 분석 목적: 가격 변동성이 크고 공포 심리가 강한 구간을 파악하여
# 개인투자자를 위한 위험 경고 방안을 제안한다.

import numpy as np
# CSV 파일 불러오기 (첫 번째 헤더 행 제외)
data = np.genfromtxt('./btc_with_fgi_4h_clean_no.csv',delimiter=',',skip_header=1)
# 데이터 열 구성
# [0] no   [1] open   [2] close
# [3] high [4] low    [5] Fear & Greed Index
no = data[:, 0]       # 데이터 번호
open_price = data[:, 1]  # 시가
close = data[:, 2]    # 종가
high = data[:, 3]     # 고가
low = data[:, 4]      # 저가
fgi = data[:, 5]      # 공포·탐욕 지수
# Step 1: 데이터 기초 현황 진단 (Statistics)
# 미션: 핵심 지표 A의 평균값과 최댓값을 구하세요.
# 비트코인 고가를 핵심 지표로 선정하여 평균과 최댓값 산출
HighBitAverage = np.mean(high)
HighBitMax = np.max(high)
print("Step 1")
print("평균 고가:", HighBitAverage)
print("최대 고가:", HighBitMax)
# 의미:
# 비트코인의 전체 관측 구간에서 평균적인 고가 수준과
# 가장 높은 가격을 확인하여 기초적인 가격 현황을 파악한다.
# Step 2: 특정 그룹 필터링 (Boolean Indexing)
# 미션: 조건 1 또는 조건 2를 만족하는 위험 그룹은 몇 개인가요?
# 조건 1: 종가가 시가보다 낮은 하락 구간
# 조건 2: 공포·탐욕 지수가 25 미만인 극단적 공포 구간
# | 연산자를 이용하여 둘 중 하나라도 만족하는 구간 추출
risk_candidate = (close < open_price) | (fgi < 25)
# True는 1로 계산되므로 조건을 만족하는 구간의 개수 산출
risk_count = np.sum(risk_candidate)
print("\nStep 2")
print("위험 분석 후보 구간 수:", risk_count)
# 의미:
# 가격이 하락했거나 극단적인 공포 심리가 나타난 구간을
# 위험 분석이 필요한 후보 구간으로 분류한다.
# 단, 모든 하락 구간이 실제 고위험 구간이라는 뜻은 아니다.


# ==================================================
# Step 3: 집중관리지수 산출 (Broadcasting)
# ==================================================

# 미션: 새로운 집중관리지수를 생성하고
# 지수가 가장 높은 대상의 ID를 찾으세요.
# 시가 대비 고가와 저가의 차이를 백분율로 계산
# 집중관리지수 = (고가 - 저가) / 시가 * 100
# 지수가 높을수록 가격 변동 폭이 큰 구간으로 판단
집중관리지수 = ((high - low) / open_price) * 100
# 집중관리지수가 가장 높은 배열 인덱스 찾기
max_idx = np.argmax(집중관리지수)
# 배열 인덱스를 이용해 원본 데이터 번호 확인
print("\nStep 3")
print("대상 ID:", int(no[max_idx]))
print("최대 집중관리지수:", 집중관리지수[max_idx], "%")
# 의미:
# 전체 데이터 중 가격 변동 폭이 가장 큰 구간을 찾는다.
# 해당 구간은 추가적인 위험 분석이 필요한 워스트 케이스로 선정한다.
# 단, 가격 변동 폭은 실제 투자 손실률을 의미하지 않는다.


# Step 4: 다중 조건 논리 분석 (Boolean Indexing)
# 미션: 조건 1과 조건 2를 동시에 만족하는 복합 위험군은
# 전체의 몇 %인가요?
# 집중관리지수 평균을 고변동성 판단 기준으로 설정
기준값 = np.mean(집중관리지수)
# 조건 1: 집중관리지수가 평균 이상
# 조건 2: 공포·탐욕 지수가 25 미만 (극단적 공포)
# & 연산자로 두 조건을 동시에 만족하는 구간 확인
risk_group = (집중관리지수 >= 기준값) & (fgi < 25)
# True는 1, False는 0으로 계산
# 조건 충족 구간 수 / 전체 구간 수 * 100
percent = np.sum(risk_group) / len(risk_group) * 100
print("평균 집중관리지수:", 기준값)
print("복합 위험 구간 수:", np.sum(risk_group))
print("복합 위험 구간 비율:", percent, "%")
# 분석 결과: 약 9.18% (기존 실행 결과 기준)
# 의미:
# 전체 비트코인 데이터 중 약 9.18%의 구간에서
# 평균 이상의 가격 변동성과 극단적 공포 심리가 동시에 나타났다.
# 따라서 해당 구간은 추가적인 위험 분석이 필요하다고 판단한다.


# ==================================================
# Step 5: 상대적 우선순위 결정 (Normalization)
# ==================================================

# 미션: 핵심 지표를 0~1 사이로 정규화하고
# 점수가 0.9 이상인 최우선 관리 대상을 추출하세요.

# Step 3에서 계산한 집중관리지수를 정규화
# 공식: (값 - 최솟값) / (최댓값 - 최솟값)

Normalization = (
    (집중관리지수 - np.min(집중관리지수))
    / (np.max(집중관리지수) - np.min(집중관리지수))
)

# 정규화 점수가 0.9 이상인 구간 선택
priority_mask = Normalization >= 0.9

# 선택된 구간의 원본 데이터 전체 추출
priority_group = data[priority_mask]

print("\nStep 5")
print("최우선 관리 구간 수:", len(priority_group))
print("대상 데이터 번호:", priority_group[:, 0])
print("최우선 관리 구간 정보:")
print(priority_group)

# 의미:
# 전체 관측 범위에서 가격 변동 폭이 최댓값에 가까운 구간을
# 최우선 관리 대상으로 선정한다.
# 해당 구간을 우선 분석하여 투자 위험 안내에 활용할 수 있다.